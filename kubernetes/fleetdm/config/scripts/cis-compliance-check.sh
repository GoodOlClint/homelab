# logging function
logmessage(){
  local level="${2:-INFO}"
  local timestamp=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
  local message="$1"

  # Format: [LEVEL] [TIMESTAMP] MESSAGE
  local log_entry="[$level] [$timestamp] $message"

  # Always log to file
  echo "$log_entry" >> "$audit_log"

  # Handle quiet levels for console output
  if [[ ! $quiet ]]; then
    echo "$log_entry"
  elif [[ ${quiet[2][2]} == 1 ]]; then
    if [[ "$message" == *"failed"* ]] || [[ "$message" == *"exemption"* ]]; then
      echo "$log_entry"
    fi
  fi
}

csv_escape(){
  # Escape a field per RFC 4180: double any embedded double quotes, then wrap
  # the whole field in double quotes so commas, quotes, CR and LF are literal.
  local field="$1"
  local quote='"'
  field="${field//$quote/$quote$quote}"
  field="$quote$field$quote"
  printf '%s' "$field"
}

logcsv(){
  local rule_name="$1"
  local result_status="$2"
  local result="$3"
  local expected="$4"
  local exemption="$5"

  if [[ ! -f "$audit_csv" ]]; then
    printf '%s\n' "Rule,Status,Result,Expected,Exemption" > "$audit_csv"
  fi

  # Use printf, not echo: under zsh `echo` interprets backslash escapes in the
  # field values (e.g. an embedded `\c` truncates the line), which would corrupt
  # the CSV even after csv_escape() has quoted each field.
  printf '%s\n' "$(csv_escape "$rule_name"),$(csv_escape "$result_status"),$(csv_escape "$result"),$(csv_escape "$expected"),$(csv_escape "$exemption")" >> "$audit_csv"
}

ask() {
  # if fix flag is passed, assume YES for everything
  if [[ $fix ]] || [[ $cfc ]]; then
    return 0
  fi

  while true; do
    if [ "${2:-}" = "Y" ]; then
      prompt="Y/n"
      default=Y
    elif [ "${2:-}" = "N" ]; then
      prompt="y/N"
      default=N
    else
      prompt="y/n"
      default=
    fi

    # Ask the question - use /dev/tty in case stdin is redirected from somewhere else
    printf "${YELLOW} $1 [$prompt] ${STD}"
    read REPLY

    # Default?
    if [ -z "$REPLY" ]; then
      REPLY=$default
    fi

    # Check if the reply is valid
    case "$REPLY" in
      Y*|y*) return 0 ;;
      N*|n*) return 1 ;;
    esac
  done
}

