print_json(){
  json_results="{"
  for key in ${(k)results_array}; do
    value="${results_array[$key]}"
    if [[ "$value" == "true" ]] || [[ "$value" == "false" ]]; then
      json_results+="\"${key}\":${value},"
    elif [[ "$value" =~ '^-?[0-9]+$' ]]; then
      json_results+="\"${key}\":${value},"
    elif [[ "$value" =~ '^-?[0-9]*\.[0-9]+$' ]]; then
      json_results+="\"${key}\":${value},"
    else
      escaped_value=$(printf '%s' "$value" | /usr/bin/jq -Rs '.')
      json_results+="\"${key}\":${escaped_value},"
    fi
  done

  json_results="${json_results%,}"
  json_results+="}"

  printf '%s\n' "$json_results" | /usr/bin/jq '.'
}

